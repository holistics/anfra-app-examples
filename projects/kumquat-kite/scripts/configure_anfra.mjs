#!/usr/bin/env node
// Writes Anfra's data source (.anfra/data_sources.yml, git-ignored, 0600) for the SELECT-only `anfra_reader` login on
// the app's PostgreSQL database, from KK_DB_HOST, KK_DB_PORT, KK_DB_NAME and ANFRA_DB_PASSWORD, and the committed
// placeholder data_sources.yml.example. Nothing secret is printed.
//   node scripts/configure_anfra.mjs [--repo <dir>]     default: anfra/ (the repo the app server and bin/anfra use)
import fs from 'node:fs';
import path from 'node:path';
import { loadEnv, required, ROOT } from './lib/env.mjs';
import { dbSettings } from './lib/db.mjs';

// Every value is written as a double-quoted YAML string (JSON string syntax), so a generated password with YAML's
// special characters (# : ! & * @ ' ") is read as it is.
const q = (v) => JSON.stringify(String(v));
const yaml = (s, password) => `# Generated by scripts/configure_anfra.mjs. The only data source of this repo: the Kumquat Kite POC's PostgreSQL
# database, read through the dedicated SELECT-only role (reporting views only, read-only transactions).
data_sources:
  kumquat_poc:
    type: postgresql
    connection:
      host: ${q(s.host)}
      port: ${s.port}
      user: "anfra_reader"
      password: ${q(password)}
      dbname: ${q(s.database)}
`;

export function writeDataSource(repo = path.join(ROOT, 'anfra')) {
  const env = loadEnv();
  required(env, 'ANFRA_DB_PASSWORD');
  const s = dbSettings(env);
  const dir = path.join(repo, '.anfra');
  fs.mkdirSync(dir, { recursive: true });
  const real = path.join(dir, 'data_sources.yml');
  fs.writeFileSync(real, yaml(s, env.ANFRA_DB_PASSWORD), { mode: 0o600 });
  fs.chmodSync(real, 0o600);
  fs.writeFileSync(path.join(dir, 'data_sources.yml.example'), yaml({ host: '<KK_DB_HOST>', port: '<KK_DB_PORT>', database: '<KK_DB_NAME>' }, '<ANFRA_DB_PASSWORD>'));
  return { file: real, settings: s };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--help')) { console.log('Usage: node scripts/configure_anfra.mjs [--repo <dir>]'); process.exit(0); }
  const i = process.argv.indexOf('--repo');
  const { file, settings } = writeDataSource(i > 0 ? path.resolve(process.argv[i + 1]) : undefined);
  console.log(`wrote ${path.relative(ROOT, file)} (0600) for anfra_reader on ${settings.database} at ${settings.host}:${settings.port}`);
}
