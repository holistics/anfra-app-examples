"""Write definitions.js (apps/mouka/js/core, plus apps/archive/wealthfolio/js where the archive exists) from the dataset AML: metric → label, description, definition.

    python3 -I scripts/gen_definitions.py          # after any AML edit (the video beats run it too)
    python3 -I scripts/gen_definitions.py --check  # self-test: parse known metrics, exit 1 on a miss
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# the official app carries its own copy; the archived looks all read archive/wealthfolio's
OUTS = [ROOT / "apps" / "mouka" / "js" / "core" / "definitions.js", ROOT / "apps" / "archive" / "wealthfolio" / "js" / "definitions.js"]
METRIC = re.compile(r"^  metric (\w+) \{\n(.*?)^  \}", re.S | re.M)
LABEL = re.compile(r"""label: (['"])((?:(?!\1).|\\.)*)\1""")
DESC1 = re.compile(r"description: '((?:[^'\\]|\\.)*)'")
DESC3 = re.compile(r"description: '''(.*?)'''", re.S)
DEFN = re.compile(r"definition: @aql (.*?) ;;", re.S)


def parse(text: str) -> dict[str, dict]:
    out = {}
    for name, body in METRIC.findall(text):
        label = LABEL.search(body)
        desc = DESC3.search(body) or DESC1.search(body)
        defn = DEFN.search(body)
        out[name] = {"label": label.group(2).replace("\\'", "'") if label else name,
                     "description": (desc.group(1).replace("\\'", "'").strip() if desc else ""),
                     "definition": " ".join(defn.group(1).split()) if defn else ""}
    return out


def main() -> None:
    defs = {p.name.split(".")[0]: parse(p.read_text()) for p in sorted((ROOT / "datasets").glob("*.dataset.aml"))}
    if "--check" in sys.argv:
        need = {"personal_finance": ["spend", "cash_flow_net", "untagged_spend_lines"],
                "wealth": ["net_worth_daily", "net_worth", "twr", "max_drawdown", "holding_value"]}
        missing = [f"{d}.{m}" for d, ms in need.items() for m in ms if not defs.get(d, {}).get(m, {}).get("definition")]
        print("missing:", missing or "none")
        sys.exit(1 if missing else 0)
    for out in OUTS:
        if not out.parent.is_dir():   # the archived looks are not in every copy of the repo
            continue
        out.write_text("// GENERATED by scripts/gen_definitions.py from datasets/*.dataset.aml. Do not edit.\n"
                       f"window.WF = window.WF || {{}};\nWF.DEFS = {json.dumps(defs, ensure_ascii=False, indent=1)};\n")
        print(f"wrote {out.relative_to(ROOT)}: " + ", ".join(f"{d} {len(m)}" for d, m in defs.items()))


if __name__ == "__main__":
    main()
