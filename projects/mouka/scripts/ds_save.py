"""The design panel's save helper: writes named design presets into apps/mouka/ds/presets.js.

The app runs in Anfra's sandboxed frame (no storage, no file access), so the panel's Save POSTs here instead.

    python3 -I scripts/ds_save.py          # serve on 127.0.0.1:7879 until Ctrl-C
    python3 -I scripts/ds_save.py --check  # self-test: validation + a write/read round trip in a temp dir

Endpoints (JSON in, JSON out, CORS * because the sandboxed frame's origin is "null"):
    GET    /health            → {"ok": true, "presets": n}
    GET    /presets           → {"ok": true, "presets": [...]}
    POST   /presets           {"name", "theme", "overrides": {"--token": "value"}} → saves (same name = update)
    DELETE /presets/<slug>    → removes one

Safety: it binds 127.0.0.1 only, writes exactly one file (never a path from the request), and validates everything:
the name is at most 40 characters, the slug is derived here, the theme must be one of DS.THEMES (read from
js/ds/tokens.js), token names match ^--[a-z0-9-]+$, and values are short and cannot open or close a CSS block or a tag.
The file is replaced atomically.
"""
from __future__ import annotations

import json
import os
import re
import sys
import tempfile
import time
import unicodedata
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "apps" / "mouka"
OUT = APP / "ds" / "presets.js"
HOST, PORT = "127.0.0.1", 7879
MAX_BODY = 64 * 1024
MAX_PRESETS = 50
KEY = re.compile(r"^--[a-z0-9-]{1,60}$")
BAD_VALUE = re.compile(r"[<>{};\\]|/\*|\*/|@import|url\s*\(|expression\s*\(", re.I)
HEADER = ("// GENERATED by scripts/ds_save.py from the design panel's Save. Do not edit by hand: save, update or delete presets in the panel\n"
          "// (press \\ in the app) with the helper running (python3 -I scripts/ds_save.py). Read by js/ds/tokens.js (DS.PRESETS).\n")
LIST_RE = re.compile(r"^window\.DS_PRESETS = (\[.*?\]);$", re.S | re.M)


def themes(app: Path = APP) -> list[str]:
    m = re.search(r"const THEMES = \[([^\]]*)\]", (app / "js" / "ds" / "tokens.js").read_text())
    return re.findall(r"'([a-z0-9-]+)'", m.group(1)) if m else ["mouka"]


def slugify(name: str) -> str:
    s = unicodedata.normalize("NFD", name.lower()).replace("đ", "d")
    s = "".join(c for c in s if not unicodedata.combining(c))
    return re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:40] or "preset"


def validate(body: object, allowed_themes: list[str]) -> dict:
    if not isinstance(body, dict):
        raise ValueError("expected a JSON object")
    name = re.sub(r"\s+", " ", str(body.get("name", ""))).strip()
    if not name or len(name) > 40 or any(ord(c) < 32 for c in name):
        raise ValueError("the name must be 1 to 40 printable characters")
    theme = body.get("theme")
    if theme not in allowed_themes:
        raise ValueError(f"unknown theme {theme!r}")
    overrides = body.get("overrides")
    if not isinstance(overrides, dict) or len(overrides) > 200:
        raise ValueError("overrides must be an object of at most 200 tokens")
    clean = {}
    for k, v in overrides.items():
        if not isinstance(k, str) or not KEY.match(k):
            raise ValueError(f"bad token name {k!r}")
        if not isinstance(v, str) or not v.strip() or len(v) > 200 or BAD_VALUE.search(v):
            raise ValueError(f"bad value for {k}")
        clean[k] = v.strip()
    return {"slug": slugify(name), "name": name, "theme": theme, "overrides": clean}


def read(out: Path = OUT) -> list[dict]:
    if not out.exists():
        return []
    m = LIST_RE.search(out.read_text())
    return json.loads(m.group(1)) if m else []


def write(presets: list[dict], last: dict | None, out: Path = OUT) -> None:
    text = (HEADER + f"window.DS_PRESETS = {json.dumps(presets, ensure_ascii=False, indent=2)};\n"
            + f"window.DS_LAST_SAVED = {json.dumps(last)};\n")
    fd, tmp = tempfile.mkstemp(prefix=".presets.", suffix=".js", dir=out.parent)
    with os.fdopen(fd, "w") as f:
        f.write(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, out)


def save(body: object, out: Path = OUT, app: Path = APP) -> dict:
    p = validate(body, themes(app))
    presets = read(out)
    p["savedAt"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    k = next((i for i, x in enumerate(presets) if x.get("slug") == p["slug"]), None)
    if k is None and len(presets) >= MAX_PRESETS:
        raise ValueError(f"at most {MAX_PRESETS} presets: delete one first")
    if k is None:
        presets.append(p)
    else:
        presets[k] = p
    write(presets, {"slug": p["slug"], "at": int(time.time() * 1000)}, out)
    return {"ok": True, "slug": p["slug"], "name": p["name"], "updated": k is not None, "presets": presets}


def delete(slug: str, out: Path = OUT) -> dict:
    presets = read(out)
    keep = [x for x in presets if x.get("slug") != slug]
    if len(keep) == len(presets):
        raise KeyError(slug)
    write(keep, None, out)
    return {"ok": True, "presets": keep}


class Handler(BaseHTTPRequestHandler):
    server_version = "ds-save/1"

    def _send(self, code: int, obj: dict) -> None:
        data = json.dumps(obj, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self._cors()
        self.end_headers()
        self.wfile.write(data)

    def _cors(self) -> None:
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, DELETE, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.send_header("Access-Control-Allow-Private-Network", "true")

    def do_OPTIONS(self) -> None:  # noqa: N802 (http.server naming)
        self.send_response(204)
        self._cors()
        self.end_headers()

    def do_GET(self) -> None:  # noqa: N802
        if self.path == "/health":
            return self._send(200, {"ok": True, "presets": len(read())})
        if self.path == "/presets":
            return self._send(200, {"ok": True, "presets": read()})
        self._send(404, {"ok": False, "error": "not found"})

    def do_POST(self) -> None:  # noqa: N802
        if self.path != "/presets":
            return self._send(404, {"ok": False, "error": "not found"})
        n = int(self.headers.get("Content-Length") or 0)
        if n <= 0 or n > MAX_BODY:
            return self._send(413, {"ok": False, "error": "body too large or empty"})
        try:
            res = save(json.loads(self.rfile.read(n)))
        except (ValueError, json.JSONDecodeError) as e:
            return self._send(400, {"ok": False, "error": str(e)})
        print(f"saved {res['slug']!r} ({'update' if res['updated'] else 'new'}) → {OUT.relative_to(ROOT)}", flush=True)
        self._send(200, res)

    def do_DELETE(self) -> None:  # noqa: N802
        m = re.fullmatch(r"/presets/([a-z0-9-]{1,40})", self.path)
        if not m:
            return self._send(404, {"ok": False, "error": "not found"})
        try:
            res = delete(m.group(1))
        except KeyError:
            return self._send(404, {"ok": False, "error": "no such preset"})
        print(f"deleted {m.group(1)!r}", flush=True)
        self._send(200, res)

    def log_message(self, *args) -> None:  # quiet: one line per save / delete above
        pass


def check() -> int:
    with tempfile.TemporaryDirectory() as d:
        app = Path(d) / "app"
        (app / "js" / "ds").mkdir(parents=True)
        (app / "ds").mkdir()
        (app / "js" / "ds" / "tokens.js").write_text("const THEMES = ['mouka', 'calm', 'dark', 'contrast'];")
        out = app / "ds" / "presets.js"
        good = {"name": "Warm  test", "theme": "mouka", "overrides": {"--r-lg": "4px", "--sans": "'DM Sans', sans-serif"}}
        r = save(good, out, app)
        assert r["slug"] == "warm-test" and not r["updated"] and read(out)[0]["name"] == "Warm test", r
        assert save({**good, "name": "Warm test"}, out, app)["updated"]
        assert save({"name": "Đêm tối", "theme": "dark", "overrides": {}}, out, app)["slug"] == "dem-toi"
        bad = [{"name": "", "theme": "mouka", "overrides": {}}, {"name": "x" * 41, "theme": "mouka", "overrides": {}},
               {"name": "a", "theme": "neon", "overrides": {}}, {"name": "a", "theme": "mouka", "overrides": {"color": "red"}},
               {"name": "a", "theme": "mouka", "overrides": {"--x": "red; } body { display:none"}},
               {"name": "a", "theme": "mouka", "overrides": {"--x": "url(http://evil)"}},
               {"name": "a", "theme": "mouka", "overrides": {"--x": "</script><script>"}}]
        for b in bad:
            try:
                save(b, out, app)
            except ValueError:
                continue
            raise AssertionError(f"accepted {b}")
        assert len(delete("warm-test", out)["presets"]) == 1 and "DS_LAST_SAVED = null" in out.read_text()
    print("ds_save --check: PASS (validation + round trip)")
    return 0


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check())
    srv = ThreadingHTTPServer((HOST, PORT), Handler)
    print(f"ds_save: http://{HOST}:{PORT} → {OUT.relative_to(ROOT)} ({len(read())} presets). Ctrl-C to stop.", flush=True)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass
